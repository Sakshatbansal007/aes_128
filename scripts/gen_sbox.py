#!/usr/bin/env python3

def gmul(a, b):
    p = 0
    for _ in range(8):
        if b & 1:
            p ^= a
        hi = a & 0x80
        a = (a << 1) & 0xFF
        if hi:
            a ^= 0x1B
        b >>= 1
    return p

def ginv(a):
    if a == 0:
        return 0
    for x in range(1, 256):
        if gmul(a, x) == 1:
            return x

def rotl8(x, n):
    return ((x << n) | (x >> (8 - n))) & 0xFF

def sbox_val(a):
    b = ginv(a)
    return b ^ rotl8(b, 1) ^ rotl8(b, 2) ^ rotl8(b, 3) ^ rotl8(b, 4) ^ 0x63

SBOX = [sbox_val(i) for i in range(256)]
INV = [0] * 256
for i, v in enumerate(SBOX):
    INV[v] = i

assert SBOX[0x00] == 0x63 and SBOX[0x01] == 0x7C and SBOX[0x53] == 0xED

def emit(name, table):
    s = f"module {name}(input [7:0] in, output reg [7:0] out);\n"
    s += "    always @(*) begin\n        case (in)\n"
    for i, v in enumerate(table):
        s += f"            8'h{i:02x}: out = 8'h{v:02x};\n"
    s += "            default: out = 8'h00;\n        endcase\n    end\nendmodule\n"
    return s

with open("rtl/sbox.v", "w") as f:
    f.write("// AUTO-GENERATED by scripts/gen_sbox.py - do not edit by hand\n")
    f.write(emit("sbox", SBOX) + "\n" + emit("inv_sbox", INV))
print("wrote rtl/sbox.v")
